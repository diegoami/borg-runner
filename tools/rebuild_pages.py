#!/usr/bin/env python3
"""Put an archived run's page back together, from its record and its keys.

`borg_runner report --all` rebuilds a run's page from the run's working
directory, and the working directory is scratch: it is not in git, and the
screens are not archived either. So a page whose run has been cleaned up
cannot be rebuilt - which is what the report says when it finds one:

    replay: <name> has no screens left; replay its keys first

Which is a half answer, because the keys are in the archive and the screens
come back from them - what is missing is the rest of the run: the record, the
decisions, the notebook and the player's own write-up, none of which a
replay writes.

So this puts the two halves together and rebuilds the page:

    python tools/rebuild_pages.py            # every archived run
    python tools/rebuild_pages.py sonnet-1  # just one

It does not change the run. The screens a replay produces are byte for byte
the screens the run saw (D6), and the files it copies are the ones the
archive kept, so the page that comes out is the page that was archived, with
whatever the page itself has gained since.
"""
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src'))

from borg_runner import report as report_module       # noqa: E402

RECORDS = Path('records')
RUNS = Path('runs')
HEADER = '<!-- borg-runner: links, regenerated by `archive` -->'
# The files the archive keeps. The screens and the questions are not among
# them: a replay writes those.
KEPT = ('record.json', 'started.json', 'notebook.md', 'standing.json',
        'inherited.json', 'input.txt', 'model-calls.jsonl')
# One ask on the page is one block of the timeline.
ASK_BLOCK = re.compile(r'<details class="ask">')
# The facts table, and the row that says how a replay of this run went.
FACTS = re.compile(r'<tr><td>(?P<key>[^<]*)</td><td>(?P<value>[^<]*)</td></tr>')


def players_own(text):
    """The write-up as the player wrote it, without the generated links.

    `archive` puts a block of links on top of the player's words, and the
    page reads the player's words, so the block is taken off again.
    """
    if HEADER in text:
        text = text.split('---\n\n', 1)[-1]
    return text.lstrip('\n')


def rows(path):
    """The decisions a file holds, in order."""
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines()
            if line.strip()]


def archived_page(name):
    """The page that is in the archive, or nothing."""
    page = RECORDS / name / 'report.html'
    return page.read_text() if page.exists() else None


def archived_asks(name):
    """How many asks the archived page shows."""
    page = archived_page(name)
    return len(ASK_BLOCK.findall(page)) if page is not None else None


def archived_verdict(name):
    """What the archived page says about a replay of this run, if it says.

    The archive keeps the record, the keys and the decisions, but not the
    verdict of a replay - and a run that was replayed shows it in its facts
    table. The page is where that verdict still is, so it is read back from
    there rather than invented: a rebuild must not change what the archive
    says about a run.
    """
    page = archived_page(name)
    if page is None:
        return None
    table = re.search(r'<table class="facts">(.*?)</table>', page, re.S)
    if not table:
        return None
    for row in FACTS.finditer(table.group(1)):
        if row.group('key') == 'replay':
            return row.group('value') == 'identical'
    return None


def decisions_for(name, live):
    """The run's decisions: the archived ones, and the asks after them.

    `stop` answers the ask the game is waiting on with the save-and-quit
    keys, and those answers are decisions like any other. A run archived
    before it stopped keeps them out of the record - and a page rebuilt
    later, from the run's working directory, has them, because by then the
    working directory did. So the two are put back together here, and the
    archived page says how many asks there were.
    """
    archived = rows(RECORDS / name / 'decisions.jsonl')
    replayed = rows(live / 'decisions.jsonl')
    kept = list(archived)
    for entry in replayed:
        if entry['ask'] > len(kept):
            kept.append(entry)
    wanted = archived_asks(name)
    if wanted is not None:
        kept = kept[:wanted]
    return kept


def prepare(name):
    """The run's working directory, put back together. None if it is gone."""
    archived, live = RECORDS / name, RUNS / name
    if not (live / 'ask').is_dir():
        return None
    for what in KEPT:
        if (archived / what).exists():
            shutil.copy(archived / what, live / what)
    decisions = decisions_for(name, live)
    if decisions:
        (live / 'decisions.jsonl').write_text(
            ''.join(json.dumps(entry, sort_keys=True) + '\n'
                    for entry in decisions))
    writeup = archived / 'REPORT.md'
    if writeup.exists():
        (live / 'REPORT.md').write_text(players_own(writeup.read_text()))
    # The verdict of a replay is not part of the run - the archive does not
    # keep it - but a run that was replayed shows it in its facts table, so
    # the page that is in the archive is where it is read back from.
    verdict = archived_verdict(name)
    if verdict is None:
        (live / 'replay.json').unlink(missing_ok=True)
    else:
        (live / 'replay.json').write_text(json.dumps(
            {'schema': 'borg-runner/replay@1', 'identical': verdict},
            indent=2, sort_keys=True) + '\n')
    return live


def rebuild(names):
    done, missing = [], []
    for name in names:
        record = RECORDS / name / 'record.json'
        if not record.exists():
            missing.append(name)
            continue
        if prepare(name) is None:
            missing.append(name)
            continue
        report_module.write(RUNS / name, into=RECORDS / name / 'report.html')
        done.append(name)
    return done, missing


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    names = argv or sorted(path.parent.name
                           for path in RECORDS.glob('*/record.json'))
    done, missing = rebuild(names)
    for name in done:
        print(f'page: records/{name}/report.html')
    for name in missing:
        print(f'page: {name} has no screens to rebuild from; replay its keys '
              f'first (borg_runner replay --run records/{name} '
              f'--into runs/{name})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
