"""Did a finished run leave everything a finished run should leave?

Eleven runs in, the answer has been no three times, each time differently: a
report written after `archive` so the archive never had it, a `record` without
`--model`, a playbook rewritten over somebody else's. Each was found by
reading the directory afterwards, which is not a method.

So this reads it for you. It checks what the prompts ask for, nothing more:
the files `archive` keeps, the fields `record` fills, the notebook `keep`
promotes, the family page the run wrote back to, the dashboard row, and
whether git has it. Every check says what it looked for, so a failure names
the command that was missed rather than a rule.

    python -m borg_runner audit --run minimaxflash-2.2
    python -m borg_runner audit --all
"""
import hashlib
import json
import subprocess
from pathlib import Path

from . import pins, run as run_module

# What `archive` keeps, and what each is for. `tools/` is checked separately,
# because a run that wrote no tools is not missing anything.
EXPECTED = {
    'record.json': 'record --run <run> --model <provider>/<version>',
    'input.txt': 'the keys, which with the seed are the whole recording',
    'decisions.jsonl': 'the reasons, written by `answer`',
    'notebook.md': 'the notes, written by `answer --note`',
    'REPORT.md': 'the write-up: both prompts ask for it before the commands',
    'report.html': 'the replay page, generated by `archive`',
    'started.json': 'the seed and the build, written by `play`',
}


def _check(ok, what, fix=None, warn=False):
    return {'ok': bool(ok), 'what': what, 'fix': fix, 'warn': warn}


# A session converted from somewhere else - a person playing in a terminal,
# recorded by another tool - has no seed, no keys and no decisions, and says
# so in `source.json`. It is audited for what it does claim to be.
CONVERTED = ('record.json', 'REPORT.md', 'report.html')


def audit(name, where=None):
    """Every check for one archived run, as rows."""
    where = Path(where) if where else run_module.RECORDS
    kept = where / name
    rows = []
    if not kept.is_dir():
        return [_check(False, f'{kept} exists',
                       'archive --run runs/<run>')]
    converted = (kept / 'source.json').exists()
    wanted_files = ({name: 'kept for a converted session' for name in CONVERTED}
                    if converted else EXPECTED)
    if converted:
        rows.append(_check(True, 'source.json: a converted session, so no '
                                 'seed, keys or decisions of its own'))
    for wanted, fix in wanted_files.items():
        path = kept / wanted
        rows.append(_check(path.exists() and path.stat().st_size,
                           f'{wanted} is there and not empty', fix))
    record = {}
    if (kept / 'record.json').exists():
        try:
            record = json.loads((kept / 'record.json').read_text())
        except ValueError as problem:
            rows.append(_check(False, f'record.json parses ({problem})'))
    cost = record.get('cost') or {}
    model = cost.get('model')
    rows.append(_check(model and '/' in str(model),
                       f'the model is provider/version ({model or "missing"})',
                       'record --model anthropic/claude-sonnet-5-5'))
    rows.append(_check(cost.get('played_by'),
                       'the record says who played it',
                       'record --played-by session|opencode|codex|other'))
    # A warning, not a failure: `--playbook` arrived on 2026-11-10 and the
    # runs before it could not name a family. A run played since then that
    # names none leaves its own model's next session nothing.
    rows.append(_check(record.get('playbook'),
                       f"the record names a playbook family "
                       f"({record.get('playbook') or 'missing'})",
                       'record --playbook <family>', warn=True))
    rows.append(_check(record.get('outcome') not in (None, 'playing'),
                       f"the outcome is settled ({record.get('outcome')})",
                       'stop --run runs/<run>'))
    rows.append(_check((record.get('asks') or 0) > 0,
                       f"it answered something ({record.get('asks')} asks)"))
    rows.append(_check(record.get('character'),
                       f"the character is known ({record.get('character')})"))
    # A second answer to an old ask never reached the game but stays in the
    # log, and a replay fed the log in order diverges from the run at exactly
    # that ask. `answer` refuses them now; this catches older logs and keys
    # files written by hand.
    dupes = record.get('duplicate_answers')
    if dupes is None:
        try:
            _, duplicate_entries = run_module.played_decisions(kept)
            dupes = sorted({entry['ask'] for entry in duplicate_entries})
        except ValueError:
            dupes = []              # an unparsable log is its own check above
    rows.append(_check(not dupes,
                       'each ask was answered once',
                       f'asks {dupes} were answered twice; the first answer '
                       'is what the game played', warn=True))
    if record.get('died'):
        rows.append(_check(record.get('killed_by'),
                           f"a death names its cause ({record.get('killed_by')})"))
    if converted:
        rows.append(_check((kept / 'keys.txt').exists()
                           or (kept / 'input.txt').exists(),
                           'the keys it does have are kept', warn=True))
    keys = kept / 'input.txt'
    if keys.exists() and record.get('keys_sha256'):
        digest = hashlib.sha256(keys.read_bytes()).hexdigest()
        rows.append(_check(digest == record['keys_sha256'],
                           'the keys match the hash in the record',
                           'record --run runs/<run> (it rewrites the hash)'))
    if converted:
        promoted = None
    promoted = run_module.KNOWLEDGE / f'{name}.md'
    rows.append(_check(promoted.exists(),
                       'its notebook is promoted into knowledge/',
                       'keep --run runs/<run> - unless it added no notes of '
                       'its own, which `keep` refuses', warn=True))
    family = record.get('playbook')
    if family:
        from . import playbooks
        wrote = [row['run'] for row in playbooks.sections(family)]
        for character_class in (None, record.get('class')):
            if character_class is not None:
                wrote += [row['run'] for row in
                          playbooks.sections(family, character_class)]
        rows.append(_check(name in wrote,
                           f'it added a section to agents/{family}/',
                           f'playbook --family {family} --append - --from {name}',
                           warn=True))
    # A script written loose in the run directory - where the player's hands
    # were, not where the prompts say - is kept by `archive`'s reconcile.
    # This names one that was left behind anyway.
    live_run = run_module.RUNS / name
    if live_run.is_dir():
        missing = [path.name for path in sorted(live_run.glob('*.py'))
                   if not (kept / 'tools' / path.name).exists()]
        rows.append(_check(not missing,
                           'every script it wrote is in the record',
                           'archive --run runs/<run> again (it reconciles '
                           'loose scripts into tools/)', warn=True))
    overview = run_module.RECORDS / 'OVERVIEW.md'
    if overview.exists():
        rows.append(_check(f'[{name}]' in overview.read_text(),
                           'it has a row in the dashboard',
                           'overview'))
    try:                                  # a test's records live elsewhere
        inside = kept.resolve().relative_to(pins.ROOT.resolve())
    except ValueError:
        inside = None
    if inside is not None:
        tracked = subprocess.run(['git', 'ls-files', str(inside)],
                                 cwd=pins.ROOT, capture_output=True, text=True)
        rows.append(_check(tracked.stdout.strip(),
                           'git has the record',
                           'git add records knowledge agents index.html '
                           '&& commit'))
    return rows


def archived(where=None):
    where = Path(where) if where else run_module.RECORDS
    return sorted(path.parent.name for path in where.glob('*/record.json'))


def failures(name, where=None):
    return [row for row in audit(name, where) if not row['ok'] and not row['warn']]
